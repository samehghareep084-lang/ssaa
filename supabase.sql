create table if not exists public.reactions (
  id bigint generated by default as identity primary key,
  video_id text not null,
  visitor_id text not null,
  reaction text not null check (reaction in ('like', 'dislike')),
  created_at timestamptz not null default now(),
  unique(video_id, visitor_id)
);

create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  video_id text not null,
  name text not null default 'زائر' check (char_length(name) <= 40),
  body text not null check (char_length(body) between 1 and 600),
  created_at timestamptz not null default now()
);

alter table public.reactions enable row level security;
alter table public.comments enable row level security;

drop policy if exists "Public can read reactions" on public.reactions;
create policy "Public can read reactions" on public.reactions for select to anon using (true);

drop policy if exists "Public can add reactions" on public.reactions;
create policy "Public can add reactions" on public.reactions for insert to anon with check (true);

drop policy if exists "Public can change reactions" on public.reactions;
create policy "Public can change reactions" on public.reactions for update to anon using (true) with check (true);

drop policy if exists "Public can remove reactions" on public.reactions;
create policy "Public can remove reactions" on public.reactions for delete to anon using (true);

drop policy if exists "Public can read comments" on public.comments;
create policy "Public can read comments" on public.comments for select to anon using (true);

drop policy if exists "Public can add comments" on public.comments;
create policy "Public can add comments" on public.comments for insert to anon with check (
  char_length(name) <= 40 and char_length(body) between 1 and 600
);
